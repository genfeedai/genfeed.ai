/**
 * The route manifest: the one place a product route is declared. The workspace
 * shell inventory and breadcrumbs, the app rail, the Admin sidebar, the page
 * help catalog, the agent-output layout and the bare-root redirects in
 * `next.config.ts` all derive from it, so a route cannot be present in one
 * registry and missing from another.
 *
 * Adding a route is one entry here plus its page. `APP_ROUTES` only needs the
 * path when other code links to it. Route renames are hard cuts: delete the
 * old entry, never alias it.
 */

