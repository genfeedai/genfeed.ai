import { learningContractIdSchema } from '@genfeedai/contracts/api-types/contracts/content-learning-generation.contract';
import { z } from 'zod';

export const BRANDED_GENERATION_FEEDBACK_RATINGS = ['up', 'down'] as const;
/** Why a member gave a generation a thumbs down. */
export const BRANDED_GENERATION_FEEDBACK_REASONS = [
  'off_voice',
  'wrong_facts',
  'too_long',
  'too_generic',
  'other',
] as const;
export const BRANDED_GENERATION_FEEDBACK_WINDOW_DAYS = 30;

const rating = z.enum(BRANDED_GENERATION_FEEDBACK_RATINGS);
const reason = z.enum(BRANDED_GENERATION_FEEDBACK_REASONS);
const counter = z.number().int().min(0);

export const brandedGenerationFeedbackInputV1Schema = z
  .strictObject({
    rating,
    reasons: z.array(reason).max(BRANDED_GENERATION_FEEDBACK_REASONS.length),
  })
  .refine(
    (value) => new Set(value.reasons).size === value.reasons.length,
    'Duplicate feedback reasons',
  )
  .refine(
    (value) => value.rating === 'down' || value.reasons.length === 0,
    'Only a thumbs down carries reasons',
  );
export type BrandedGenerationFeedbackInputV1 = z.infer<
  typeof brandedGenerationFeedbackInputV1Schema
>;

/** What the saved post says about the text, read live and never stored. */
export const brandedGenerationFeedbackImplicitV1Schema = z.strictObject({
  /** The post text no longer matches the generated bytes; null with no post. */
  isEdited: z.boolean().nullable(),
  isDiscarded: z.boolean(),
  postStatus: z.string().min(1).max(64).nullable(),
  reviewDecision: z.string().min(1).max(64).nullable(),
});

/** The caller's own rating of one receipt, with the implicit signals beside it. */
export const brandedGenerationFeedbackReadV1Schema = z.strictObject({
  id: learningContractIdSchema,
  receiptId: learningContractIdSchema,
  rating: rating.nullable(),
  reasons: z.array(reason).max(BRANDED_GENERATION_FEEDBACK_REASONS.length),
  ratedAt: z.string().min(1).max(40).nullable(),
  implicit: brandedGenerationFeedbackImplicitV1Schema,
});
export type BrandedGenerationFeedbackReadV1 = z.infer<
  typeof brandedGenerationFeedbackReadV1Schema
>;

const reasonTally = z.strictObject({ reason, count: counter });
const modeTally = z.strictObject({
  mode: z.string().min(1).max(64),
  up: counter,
  down: counter,
});
/** Ratings given to a brand's generations in the window, all members together. */
export const brandedGenerationFeedbackSummaryV1Schema = z.strictObject({
  /** The brand id. */
  id: learningContractIdSchema,
  windowDays: z.number().int().min(1).max(365),
  up: counter,
  down: counter,
  /** How often each reason was given; a reason nobody gave has a zero count. */
  reasons: z.array(reasonTally).max(BRANDED_GENERATION_FEEDBACK_REASONS.length),
  byMode: z.array(modeTally).max(16),
});
export type BrandedGenerationFeedbackSummaryV1 = z.infer<
  typeof brandedGenerationFeedbackSummaryV1Schema
>;
