import type { AgentApiService } from '@genfeedai/agent/services/agent-api.service';
import { TurboRunStatus } from '@genfeedai/contracts';
import type { ITurboRunSummary } from '@genfeedai/contracts/interfaces';
import { useEffect, useState } from 'react';

const POLL_INTERVAL_MS = 3000;
const MAX_CONSECUTIVE_FAILURES = 5;

const SETTLED_STATUSES: ReadonlySet<TurboRunStatus> = new Set([
  TurboRunStatus.COMPLETED,
  TurboRunStatus.PARTIAL,
  TurboRunStatus.FAILED,
  TurboRunStatus.CANCELLED,
]);

export function isTurboRunSettled(status: TurboRunStatus): boolean {
  return SETTLED_STATUSES.has(status);
}

/**
 * Follows one run until it settles so its chat card shows real progress and
 * the drafts as they land. The run is generated by a background workflow, so
 * the approval reply can only name it; this reads the rest from the API.
 */
export function useTurboRunProgress(
  apiService: Pick<AgentApiService, 'getTurboRun'> | null,
  turboRunId: string | undefined,
): ITurboRunSummary | null {
  const [run, setRun] = useState<ITurboRunSummary | null>(null);

  useEffect(() => {
    if (!apiService || !turboRunId) {
      return;
    }

    const controller = new AbortController();
    let timer: ReturnType<typeof setTimeout> | undefined;
    let failures = 0;

    const poll = async (): Promise<void> => {
      try {
        const next = await apiService.getTurboRun(
          turboRunId,
          controller.signal,
        );
        if (controller.signal.aborted) {
          return;
        }
        failures = 0;
        setRun(next);
        if (isTurboRunSettled(next.status)) {
          return;
        }
      } catch {
        if (controller.signal.aborted) {
          return;
        }
        failures += 1;
        // The card keeps its last known state; stop hammering a failing API.
        if (failures >= MAX_CONSECUTIVE_FAILURES) {
          return;
        }
      }
      timer = setTimeout(() => void poll(), POLL_INTERVAL_MS);
    };

    void poll();

    return () => {
      controller.abort();
      if (timer) {
        clearTimeout(timer);
      }
    };
  }, [apiService, turboRunId]);

  return run;
}
