import type {
  ToolAnnotations,
  ToolCategory,
  ToolDataSource,
  ToolMcpCardKind,
  ToolMutationPolicy,
  ToolUiActionType,
} from '../interfaces/tool-policy.interface';
import type { ToolsetName } from './toolset-names';

export type CuratedActionSurface = 'agent' | 'mcp' | 'workflow';

/** Confirmation-matrix class of a write tool (#4672); see `agent-action-class.ts`. */
export type CuratedActionClass =
  | 'brand-context'
  | 'credit-spending'
  | 'outbound';

/**
 * Which Claude-restricted MCP grant may call the tool: the MCP endpoint, the
 * onboarding agent adapter, or both. Absent means standard grants only.
 */
export type CuratedClaudeAccess = 'agent' | 'both' | 'mcp';

/**
 * Reviewed MCP annotation hint, applied over the defaults derived from the
 * mutation policy: `destructive` pins a write that deletes or overwrites,
 * `read-only` pins a read the name classifier misses, and
 * `non-destructive-write` marks a write that only adds data.
 */
export type CuratedAnnotationHint =
  | 'destructive'
  | 'non-destructive-write'
  | 'read-only';

/**
 * The one definition of a tool's surface, access and policy. Every name-keyed
 * map the registry used to keep (mutation policy, confirmation class, Claude
 * grants, MCP annotations, data source, brand requirement) is derived from
 * these fields, so adding or renaming a tool edits one entry here, plus its
 * schema in `source/` and its handler. Keep keys sorted.
 */
export interface CuratedActionCatalogEntry {
  /** Confirmation class; absent for reads and ordinary writes. */
  actionClass?: CuratedActionClass;
  annotationHint?: CuratedAnnotationHint;
  /** Full MCP annotation replacement for a handler the default rules misstate. */
  annotationOverride?: ToolAnnotations;
  category: ToolCategory;
  claudeAccess?: CuratedClaudeAccess;
  /** Absent means the tool reads our own database (`stored`). */
  dataSource?: Exclude<ToolDataSource, 'stored'>;
  /** Credit spender whose MCP approval the organization setting may never waive. */
  isMcpApprovalNeverSkipped?: true;
  /** Reaches a live third party or the open web beyond what the default rules detect. */
  isOpenWorld?: true;
  isPublishingApprovalRequired?: true;
  /** A read whose name carries no read prefix, such as `analyze_performance`. */
  isReadOnly?: true;
  /** Card the MCP app renders the tool's result as; absent means no card. */
  mcpCardKind?: ToolMcpCardKind;
  /** Posting or media generation that always waits for a reviewer on MCP. */
  mcpApproval?: 'generation' | 'posting';
  /** MCP callers must pass `brandId` (#5786). */
  mcpBrandRequired?: true;
  /**
   * MCP callers must pass `brandId` when the organization has more than one
   * brand. A single-brand organization may omit it (#10071).
   */
  mcpBrandRequiredWhenMultiple?: true;
  /** Required for every write; reads omit it. */
  mutationPolicy?: ToolMutationPolicy;
  name: string;
  /** Tool whose quote this tool spends (`quote` credit pricing). */
  quoteTool?: string;
  surfaces: readonly [CuratedActionSurface, ...CuratedActionSurface[]];
  toolset: ToolsetName;
  uiActionType?: ToolUiActionType;
}

